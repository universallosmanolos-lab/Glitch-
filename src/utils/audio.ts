  private isMuted: boolean = false;
  private masterGain: GainNode | null = null;
  private bgmIntervalId: number | null = null;
  private bgmStep: number = 0;

  constructor() {
    const saved = localStorage.getItem('glitch_muted');
    this.isMuted = saved === 'true';
  }

  private initContext() {
    if (!this.ctx) {
      const AudioCtx = window.AudioContext || (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
      if (AudioCtx) {
        this.ctx = new AudioCtx();
        this.masterGain = this.ctx.createGain();
        this.masterGain.gain.value = this.isMuted ? 0 : 0.6;
        this.masterGain.connect(this.ctx.destination);
      }
    }
    if (this.ctx && this.ctx.state === 'suspended') {
      this.ctx.resume().catch(() => {});
    }
  }

  public userGesture() {
    this.initContext();
  }

  public getMuted(): boolean {
    return this.isMuted;
  }

  public toggleMute(): boolean {
    this.isMuted = !this.isMuted;
    localStorage.setItem('glitch_muted', String(this.isMuted));
    if (this.masterGain && this.ctx) {
      this.masterGain.gain.cancelScheduledValues(this.ctx.currentTime);
      this.masterGain.gain.setValueAtTime(this.isMuted ? 0 : 0.6, this.ctx.currentTime);
    }
    if (this.isMuted) {
      this.stopBGM();
    }
    return this.isMuted;
  }

  public startBGM() {
    if (this.bgmIntervalId !== null) return;
    this.initContext();
    this.bgmStep = 0;

    // Dynamic background rhythm / arpeggio loop
    const tempoMs = 240; // 250ms per sixteenth note / beat
    this.bgmIntervalId = window.setInterval(() => {
      if (this.isMuted || !this.ctx || !this.masterGain) return;
      try {
        const now = this.ctx.currentTime;
        const bassNotes = [110, 110, 130.81, 146.83, 110, 164.81, 130.81, 98.0];
        const freq = bassNotes[this.bgmStep % bassNotes.length];

        const osc = this.ctx.createOscillator();
        const gain = this.ctx.createGain();

        osc.type = this.bgmStep % 4 === 0 ? 'sawtooth' : 'triangle';
        osc.frequency.setValueAtTime(freq, now);

        gain.gain.setValueAtTime(0.04, now);
        gain.gain.exponentialRampToValueAtTime(0.001, now + 0.2);

        osc.connect(gain);
        gain.connect(this.masterGain);

        osc.start(now);
        osc.stop(now + 0.2);

        this.bgmStep++;
      } catch {
        // ignore
      }
    }, tempoMs);
  }

  public stopBGM() {
    if (this.bgmIntervalId !== null) {
      clearInterval(this.bgmIntervalId);
      this.bgmIntervalId = null;
    }
  }

